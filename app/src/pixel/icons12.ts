export function pixelBits(name: string): boolean[] | null {
  const rows = PIXEL_ICONS[name];
  if (!rows) return null;
  const out: boolean[] = [];
  for (let y = 0; y < 12; y++) for (let x = 0; x < 12; x++) out.push((rows[y] ?? '')[x] === '#');
  return out;
}
