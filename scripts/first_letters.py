# The first days in Lypove, told in letters: the neighbour, баба Злата Коваль, leaves one on the table of the
# house on the first morning and another each time the last was followed. No tutorial — just a kind old woman
# who knows the town and writes the way she talks: how the house lives, where the market is, where seeds are
# sold and how a garden bed says what it wants, the café, the map, the taxi, where work is found. Each letter is
# a quest of the kind "letters" (the client shows it as a letter and starts the next one by itself).
# Run inside gen_base_content.py after quests.py (it needs `quest`, `use`, `thanks`).

ZLATA_N = "res_1"

HOME_TITLE = "Лист на столі"
HOME_TEXT = ("Доброго ранку, сусіде! Це я, баба Злата з хати навпроти. Ключ ти вже знайшов, тож розповім, як тут жити.\n\n"
             "Ходиш, куди хочеш: веди пальцем по кружку внизу екрана (на комп'ютері — стрілки чи WASD) або просто торкнись "
             "підлоги там, куди треба. Підійди до речі — і велика кнопка збоку скаже, що з нею робити: сісти, лягти, "
             "зварити, увімкнути. А можна торкнутися самої речі.\n\n"
             "Двері на вулицю — ті, що з ґанком. Підійди до них і натисни «Двері» (або торкнись дверей) — і ти надворі. "
             "Назад додому — так само, через свої двері: біля них на землі світиться зелений знак. А як захочеш "
             "переставити меблі чи пофарбувати стіни — кнопка «Кімната» вгорі.\n\n"
             "Ну ж бо, виходь надвір, я тобі ще напишу.")
quest("first.home", HOME_TITLE, ZLATA_N, "home", HOME_TEXT,
      [go("Вийти з хати надвір", "village", done="Надворі пахне липою й свіжим хлібом. Баба Злата махає з лави навпроти.")],
      "«Отак! — гукає баба Злата. — Бачиш, нічого страшного. Я тобі ще лист залишу».",
      reward=thanks(hearts=[(ZLATA_N, 20)]), kind="letters")

quest("first.welcome", "Лист про дошку", ZLATA_N, "home",
      "Сусіде, це знову я. Хата в тебе добра, тільки не любить, коли її забувають. Холодильник гуде, як старий кіт, — клади туди їжу, а "
      "на плиті вари: з тарілкою супу і в мороз тепло. Ліжко біля вікна, шафа з одягом — у кутку, а скриня береже "
      "те, що не влазить в інвентар. Раз на місяць прийдуть рахунки за світло, воду, газ і сміття — неси їх у "
      "комунальну контору, бо вимкнуть і не спитають.\n\n"
      "А тепер роздивися довкола. Біля ринку, через дорогу від площі, висить дошка оголошень — там пишуть, "
      "кому чого бракує. Почитай її: так у Липовому знайомляться.",
      [use("Почитати дошку оголошень біля ринку", "st.notice_board.read",
           done="На дошці — загублений кіт, продаж велосипеда й толока біля школи. Липове одразу стає ближчим.")],
      "«От і добре, — каже баба Злата з лави. — Тепер ти вже трохи тутешній».",
      reward=thanks(hearts=[(ZLATA_N, 40)]), after=("first.home",), kind="letters")

quest("first.market", "Лист про ринок", ZLATA_N, "home",
      "Сусіде, це знову я. Бачила, як ти читав дошку, — молодець.\n\n"
      "Ринок у нас через дорогу від площі: два ряди яток, і там усе свіже. Гроші в місті заробляють руками — "
      "на пошті, в пекарні, на фермі, — а вдома, хоч як старайся, монет не набіжить. Зате вдома готують, садять і "
      "відпочивають.\n\n"
      "Купи на ринку теплу булочку — пекарка завжди підморгує новим людям. А зранку біля дверей лежатиме свіжа "
      "газета: у ній усе, що сталося вчора, і що буде завтра.",
      [use("Купити булочку на ринку", "st.stall_bread.bun", done="Булочка ще тепла, з маком. Пекарка підморгує: «Друга — завтра!»")],
      "«Смачна? — сміється баба Злата. — То ти вже наш».",
      reward=thanks(hearts=[(ZLATA_N, 30)]), after=("first.welcome",), kind="letters")

quest("first.seeds", "Лист про город", ZLATA_N, "home",
      "Сусіде, за хатою в тебе грядки — порожні, аж серце болить.\n\n"
      "Насіння продають у «Колоску» й у «Господарчому», саджанці — у «Півонії». Стань біля грядки — вона сама "
      "скаже, чого їй треба: посадити, полити чи вже збирати. Поливай щодня, коли нема дощу, а в спеку — то й "
      "двічі. Моркві треба трохи часу, як і всьому доброму.\n\n"
      "Почни з моркви: вона прощає новачкам.",
      [use("Купити насіння моркви в «Колоску»", "st.grocery.seed_carrot", done="Пакетик шелестить у кишені. Продавчиня радить сіяти рядками.")],
      "«Посади ще сьогодні, — каже баба Злата. — Земля любить, коли про неї пам'ятають».",
      reward=thanks(hearts=[(ZLATA_N, 30)]), after=("first.market",), kind="letters")

quest("first.cafe", "Лист про людей", ZLATA_N, "home",
      "Сусіде, останній лист від мене, далі вже сам.\n\n"
      "У кишені в тебе є стара паперова карта — на ній усе Липове: торкнись назви, і вона покаже, як дійти. "
      "Якщо далеко чи дощ, клич таксі, тільки в дощ воно дорожче. Роботу шукай у людей: на пошті, в пекарні, на "
      "фермі завжди треба рук, а дошка оголошень підкаже, хто чекає допомоги.\n\n"
      "А люди в нас добрі, хоч і з норовом. Зайди в кав'ярню «Липа», випий кави — там увесь город новин.",
      [use("Випити кави в «Липі»", "st.cafe.coffee", done="Бариста малює на пінці листочок липи. За сусіднім столиком сперечаються про погоду й АЕС.")],
      "«Ну все, — пише баба Злата на клаптику під дверима. — Тепер Липове твоє. А я по суботах печу пиріжки — заходь».",
      reward=thanks(coins=15, hearts=[(ZLATA_N, 50)]), after=("first.seeds",), kind="letters")
