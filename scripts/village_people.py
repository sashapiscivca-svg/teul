def slot_(f, t, *places, days=None):
    s = {"from": f, "to": t, "places": [[p, w] for p, w in places]}
    if days:
        s["days"] = days
    return s


def L(text, hearts=0, when="", at=""):
    out = {"text": text}
    if hearts:
        out["hearts"] = hearts
    if when:
        out["when"] = when
    if at:
        out["at"] = at
    return out


